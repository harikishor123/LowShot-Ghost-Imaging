#!/usr/bin/env python3
"""Photon-budget conditioning for Model B (photon-conditioned U-Net).

Model B input = [R, G, B, c] where RGB is the noisy linear-light image N/P (exactly Model A's
input) and c is a spatially constant map of the KNOWN simulated photon budget:

    c(P) = (log10(P) - log10(P_MIN)) / (log10(P_MAX) - log10(P_MIN)),  P_MIN = 10, P_MAX = 1000
         = (log10(P) - 1) / 2
    P=10 -> 0.0, 50 -> 0.3495, 100 -> 0.5, 250 -> 0.6990, 500 -> 0.8495, 1000 -> 1.0

c is derived ONLY from the sample's photon_budget_P in the photon-simulation metadata
(read via dataset_loader.read_samples), never from the clean target or image content.

The training stream subclasses dataset_loader.TrainPatchStream and calls its unchanged
_patches_from(), so patch positions, augmentation and targets are generated by the same code
and the same per-load random states as Model A; the condition channel is appended afterwards
(it is spatially constant, hence invariant to the dihedral augmentation).
"""

from __future__ import annotations

import math

import numpy as np

from dataset_loader import TrainPatchStream

P_MIN, P_MAX = 10.0, 1000.0
ALLOWED_P = (10.0, 50.0, 100.0, 250.0, 500.0, 1000.0)


def photon_condition(P: float) -> float:
    P = float(P)
    if not (P_MIN <= P <= P_MAX):
        raise ValueError(f"photon budget {P} outside the conditioned range [{P_MIN}, {P_MAX}]")
    return (math.log10(P) - math.log10(P_MIN)) / (math.log10(P_MAX) - math.log10(P_MIN))


def append_condition(x: np.ndarray, P: float) -> np.ndarray:
    """x: (..., H, W, 3) noisy RGB -> (..., H, W, 4) with a constant condition channel."""
    c = np.full(x.shape[:-1] + (1,), photon_condition(P), dtype=np.float32)
    return np.concatenate([x.astype(np.float32, copy=False), c], axis=-1)


class ConditionedTrainPatchStream(TrainPatchStream):
    """Model A's training stream with the photon-condition channel appended to each input patch."""

    def _patches_from(self, row: dict, rng_state: int):
        P = float(row["photon_budget_P"])
        return [(append_condition(x, P), y4) for x, y4 in super()._patches_from(row, rng_state)]


def condition_validation_inputs(xv: np.ndarray, Pv: np.ndarray) -> np.ndarray:
    """Append the condition channel to Model A's fixed validation patches (per-patch P)."""
    c = np.array([photon_condition(p) for p in Pv], np.float32)[:, None, None, None]
    return np.concatenate([xv, np.broadcast_to(c, xv.shape[:-1] + (1,))], axis=-1).astype(np.float32)
